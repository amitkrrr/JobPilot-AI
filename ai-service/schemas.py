from pydantic import BaseModel, Field
from typing import List, Optional, Literal

class ParseRequest(BaseModel):
    s3_key: str = Field(..., description="The S3 path/key of the resume file inside the bucket")

class ResumeProfile(BaseModel):
    name: Optional[str] = None
    email: Optional[str] = None
    phone: Optional[str] = None
    location: Optional[str] = None
    headline: Optional[str] = None
    years_of_experience: Optional[int] = 0
    current_company: Optional[str] = None
    current_role: Optional[str] = None
    linkedin_url: Optional[str] = None
    github_url: Optional[str] = None
    portfolio_url: Optional[str] = None
    skills: List[str] = Field(default_factory=list, description="Extracted technical and professional skills")
    education: List[str] = Field(default_factory=list, description="Extracted education details")
    experience: List[str] = Field(default_factory=list, description="Extracted work experience history")

class CandidateProfileContext(BaseModel):
    id: Optional[int] = None
    name: Optional[str] = None
    email: Optional[str] = None
    phone: Optional[str] = None
    location: Optional[str] = None
    headline: Optional[str] = None
    yearsOfExperience: Optional[int] = 0
    currentCompany: Optional[str] = None
    currentRole: Optional[str] = None
    linkedinUrl: Optional[str] = None
    githubUrl: Optional[str] = None
    portfolioUrl: Optional[str] = None

class ChatRequest(BaseModel):
    message: str = Field(..., description="The user's chat input message")
    profile: Optional[CandidateProfileContext] = None

class JobCardResponse(BaseModel):
    id: int
    title: str
    company: str
    location: str
    workStyle: str
    salaryInfo: Optional[str] = None
    experienceRequired: Optional[str] = None
    description: str
    sourceUrl: Optional[str] = None
    skills: List[str] = []

class AIChatResponse(BaseModel):
    response: str = Field(..., description="The textual response generated by the AI assistant")
    jobs: List[JobCardResponse] = Field(default_factory=list, description="Extracted or matching job cards to show interactive cards in chat")

class SearchIntent(BaseModel):
    intent: Literal["JOB_SEARCH", "GENERAL_CHAT"] = Field(..., description="Classified intent type")
    role: Optional[str] = Field(None, description="Target job role or title")
    skills: List[str] = Field(default_factory=list, description="Required skills extracted from message")
    location: Optional[str] = Field(None, description="Target city or 'Remote'")
    experience_min: Optional[int] = Field(None, description="Minimum years of experience")
    experience_max: Optional[int] = Field(None, description="Maximum years of experience")
    remote: bool = Field(False, description="Whether a remote role is requested")
    reply: Optional[str] = Field(None, description="Conversational reply when intent is GENERAL_CHAT")

class IntentRequest(BaseModel):
    message: str = Field(..., description="The user's raw natural language message")
    profile: Optional[CandidateProfileContext] = None
    last_intent: Optional[SearchIntent] = None

class ParseJDRequest(BaseModel):
    description: str = Field(..., description="The raw plain text of the job description to parse")

class ParsedJobRequirement(BaseModel):
    required_skills: List[str] = Field(default_factory=list, description="Mandatory core technical skills and certifications")
    preferred_skills: List[str] = Field(default_factory=list, description="Nice-to-have technologies, frameworks, and skills")
    minimum_experience: Optional[int] = Field(0, description="Minimum numeric years of experience required")
    required_education: Optional[str] = Field("None", description="Minimum educational degree or certification required")
    responsibilities: List[str] = Field(default_factory=list, description="Key duties and core responsibilities of the role")

class MatchRequest(BaseModel):
    job_description: Optional[str] = ""
    required_skills: List[str] = Field(default_factory=list)
    candidate_skills: List[str] = Field(default_factory=list)
    years_of_experience: Optional[int] = 0

class MatchResult(BaseModel):
    score: int = Field(..., description="Match score from 0 to 100")
    strengths: List[str] = Field(default_factory=list, description="Key candidate strengths matching the role")
    gaps: List[str] = Field(default_factory=list, description="Missing skills or gaps for the role")
    verdict: str = Field(..., description="Overall summary verdict on the fit")
